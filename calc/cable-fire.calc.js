/* ══════════════════════════════════════════════════════════════
   PartsOn · 금강케이블 소방용 내화케이블(TFR-8) 선정 — 순수 함수 (DOM 비의존)
   출처: cable-fire.html 무손실 추출 (계산식 불변). html은 이 모듈을
   로드하지 않는 병렬 사본이므로, html computeFire 를 고치면 여기도 동일 유지할 것.
   등급: verified — 금강케이블 카탈로그 TFR-8(p.14) 심수×SQ 라인업·완성외경·중량 실측.
   ────────────────────────────────────────────────────────────────
   TFR-8 = 0.6/1kV 트레이용 난연 내화케이블(Tray Flame Resistant, 소방 전원용).
   화재경보·비상등·스프링클러 등 내화성이 요구되는 소방 전원회로에 사용.
   선정(품번 선정기): 심수(1~4) + 공칭단면적(SQ) → 금강 TFR-8 품번·완성외경·도체저항·중량.
   ※ 전류 기반 굵기 산정(전압강하·허용전류)은 전력케이블 계산기와 동일(도체저항 공통).
     소방 제어·신호 회로는 제어케이블(내화 TFR-CVV 등급)로, 전원은 TFR-8/TFR-CV로 구분.
   ══════════════════════════════════════════════════════════════ */

const R_FIRE = { 1.5:12.1, 2.5:7.41, 4:4.61, 6:3.08, 10:1.83 };
/* 완성외경 [mm] : OD[심수][SQ] (금강 TFR-8 카탈로그 p.14) */
const OD_TFR8 = {
  1:{1.5:8.5, 2.5:9.0, 4:9.5, 6:10.0, 10:11.0},
  2:{1.5:14.0,2.5:15.0,4:16.0,6:17.5,10:19.5},
  3:{1.5:15.0,2.5:16.0,4:17.0,6:18.5,10:20.5},
  4:{1.5:16.0,2.5:17.0,4:18.5,6:20.0,10:22.5},
};
/* 개산중량 [kg/km] : W[심수][SQ] */
const W_TFR8 = {
  1:{1.5:60, 2.5:80, 4:100,6:120,10:180},
  2:{1.5:165,2.5:190,4:235,6:290,10:395},
  3:{1.5:200,2.5:230,4:290,6:365,10:510},
  4:{1.5:230,2.5:280,4:355,6:450,10:645},
};
const CORE_LIST_FIRE = [1, 2, 3, 4];
const SQ_LIST_FIRE = [1.5, 2.5, 4, 6, 10];

/* ──────────────────────────────────────────────────────────────
   입력 계약 input = { cores, sq }
   ────────────────────────────────────────────────────────────── */
function computeFire(input) {
  const need = ([1, 2, 3, 4].indexOf(+input.cores) >= 0) ? +input.cores : 1;
  const sq = (SQ_LIST_FIRE.indexOf(+input.sq) >= 0) ? +input.sq : 2.5;

  const results = CORE_LIST_FIRE.map(c => {
    const od = OD_TFR8[c][sq], w = W_TFR8[c][sq];
    const ok = c === need;
    return { cores:c, sq, od, weight:w, R:R_FIRE[sq], ok, pn: 'TFR-8 ' + c + 'C×' + sq + 'SQ' };
  });
  const recommended = results.find(r => r.ok) || null;

  const notes = [];
  notes.push('TFR-8은 소방 전원회로용 난연 내화케이블입니다. 소방 제어·신호 회로는 내화 제어케이블(TFR-CVV 등)로, 일반 전력은 VV/CV로 구분하세요.');
  notes.push('전류 기준 굵기(전압강하·허용전류) 산정은 전력케이블 계산기를 함께 활용하세요(도체저항 공통). 내화배선은 소방 관련 법규·KS를 따릅니다.');

  return { cores:need, sq, results, recommended, notes };
}

module.exports = { computeFire, R_FIRE, OD_TFR8, W_TFR8, CORE_LIST_FIRE, SQ_LIST_FIRE };
