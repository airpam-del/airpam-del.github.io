/* 심수 오름차순 목록(타입별) */
function coreList(type) { return Object.keys(OD_CTRL[type]).map(Number).sort((a, b) => a - b); }

/* ──────────────────────────────────────────────────────────────
   입력 계약 input = { shieldType:'CVV'|'CCVS', coresNeeded, sq }
   ────────────────────────────────────────────────────────────── */
function computeControl(input) {
  const type = (input.shieldType === 'CCVS') ? 'CCVS' : 'CVV';
  const need = Math.max(1, Math.round(+input.coresNeeded || 1));
  const sq = ([1.5, 2.5, 4, 6, 10].indexOf(+input.sq) >= 0) ? +input.sq : 2.5;
  const cores = coreList(type);

  // 해당 SQ에서 제공되는 심수만
  const avail = cores.filter(c => OD_CTRL[type][c][sq] != null);
  const results = avail.map(c => {
    const od = OD_CTRL[type][c][sq];
    const ok = c >= need;                 // 필요 신호수 수용 가능
    const spare = c - need;
    return { cores:c, sq, od, R:R_CTRL[sq], ok, spare, pn: CTRL_META[type].name + ' ' + c + 'C×' + sq + 'SQ' };
  });
  // 추천: 필요 이상 최소 심수
  const passing = results.filter(r => r.ok); // avail 오름차순 → 첫 적합이 최소
  const recommended = passing.length ? passing[0] : null;

  const notes = [];
  if (!recommended) notes.push('이 SQ(' + sq + '㎟)에서는 ' + need + '심 이상 제공 규격이 없습니다. SQ를 낮추거나(고심수는 작은 SQ 제공) 케이블을 분할하세요. 최대 제공 심수: ' + (avail.length ? avail[avail.length - 1] : '-') + '심.');
  notes.push('제어케이블은 신호·접점용이라 전류용량이 아닌 신호 수(심수)로 선정합니다. 노이즈 환경·인버터 주변은 차폐형(CCV-S)을 권장합니다.');

  return { shieldType:type, meta:CTRL_META[type], coresNeeded:need, sq, results, recommended, notes, availCores:avail };
}

module.exports = { computeControl, coreList, R_CTRL, OD_CTRL, CTRL_META };
